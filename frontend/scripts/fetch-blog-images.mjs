import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const API_KEY = process.env.PEXELS_API_KEY;
if (!API_KEY) {
  console.error("Missing PEXELS_API_KEY env var");
  process.exit(1);
}

const ROOT = process.argv[2]; // frontend dir
const PUBLIC_DIR = path.join(ROOT, "public", "blog");
const MANIFEST = path.join(ROOT, "src", "lib", "blog", "images.generated.ts");

// slug -> Pexels query (must match src/config/blog.ts)
const POSTS = [
  { slug: "new-vs-used-vs-cpo", query: "car dealership showroom new cars" },
  { slug: "reading-combined-ratings", query: "car salesman customer handshake dealership" },
  { slug: "best-suvs-under-30k", query: "white suv car road" },
  { slug: "financing-101", query: "car loan paperwork signing contract" },
  { slug: "electric-cars-guide", query: "electric car charging station" },
  { slug: "test-drive-questions", query: "person driving car interior steering wheel" },
  { slug: "inspect-used-car", query: "mechanic inspecting car engine" },
  { slug: "trade-in-tips", query: "car keys handover dealership" },
  { slug: "best-family-road-trip-cars", query: "family road trip car scenic highway" },
  { slug: "winter-driving-prep", query: "car driving snow winter road" },
  { slug: "understanding-carfax", query: "car documents paperwork report desk" },
  { slug: "cpo-explained", query: "luxury car showroom dealership" },
];

async function search(query, perPage = 6) {
  const url = `https://api.pexels.com/v1/search?query=${encodeURIComponent(
    query
  )}&per_page=${perPage}&orientation=landscape`;
  const res = await fetch(url, { headers: { Authorization: API_KEY } });
  if (!res.ok) {
    console.warn(`  ! search "${query}" -> HTTP ${res.status}`);
    return [];
  }
  const data = await res.json();
  return data.photos ?? [];
}

async function downloadBuffer(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

async function saveWebp(buffer, dest) {
  const sharp = (await import("sharp")).default;
  await sharp(buffer)
    .rotate()
    .resize({ width: 1600, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toFile(dest);
  return buffer.length;
}

async function main() {
  await mkdir(PUBLIC_DIR, { recursive: true });
  const manifest = {};

  for (const post of POSTS) {
    const fallbacks = [post.query, "car dealership", "car"];
    let photo = null;
    for (const q of fallbacks) {
      const photos = await search(q);
      if (photos.length) {
        photo = photos[0];
        break;
      }
    }
    if (!photo) {
      console.log(`${post.slug}: NO RESULTS`);
      continue;
    }
    const src = photo.src.large2x || photo.src.large || photo.src.original;
    const file = `${post.slug}.webp`;
    const dest = path.join(PUBLIC_DIR, file);
    try {
      const buffer = await downloadBuffer(src);
      const bytes = await saveWebp(buffer, dest);
      manifest[post.slug] = `/blog/${file}`;
      console.log(`${post.slug}: ok (${Math.round(bytes / 1024)}kb)`);
    } catch (e) {
      console.warn(`  ! download ${file}: ${e.message}`);
    }
  }

  const header =
    "// AUTO-GENERATED by scripts/fetch-blog-images.mjs — do not edit by hand.\n" +
    "// Cover images sourced from Pexels (https://pexels.com).\n\n";
  const body =
    "export const BLOG_IMAGES: Record<string, string> = " +
    JSON.stringify(manifest, null, 2) +
    ";\n";
  await writeFile(MANIFEST, header + body);
  console.log(`\nDone. ${Object.keys(manifest).length} images. Manifest -> ${MANIFEST}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
