function suffix(body) {
  if (body === "Truck") return "truck";
  if (body === "Electric") return "electric car";
  return "car";
}

async function search(query, perPage = 8) {
  const url = `https://api.pexels.com/v1/search?query=${encodeURIComponent(
    query
  )}&per_page=${perPage}&orientation=landscape`;
  const res = await fetch(url, { headers: { Authorization: API_KEY } });
  if (!res.ok) {
    console.warn(`  ! search "${query}" -> HTTP ${res.status}`);
    return [];
  }
  const data = await res.json();
  return data.photos ?? [];
}

async function photosFor(v) {
  const queries = [
    `${v.make} ${v.model} ${suffix(v.body)}`,
    `${v.make} ${v.model}`,
    `${v.make} ${suffix(v.body)}`,
    `${v.body === "Electric" ? "electric" : v.body} car`,
  ];
  for (const q of queries) {
    const photos = await search(q);
    if (photos.length >= 1) return { photos, query: q };
  }
  return { photos: [], query: null };
}

async function downloadBuffer(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

async function saveWebp(buffer, dest) {
  const sharp = (await import("sharp")).default;
  await sharp(buffer)
    .rotate()
    .resize({ width: 1600, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toFile(dest);
  return buffer.length;
}

async function main() {
  await mkdir(PUBLIC_DIR, { recursive: true });
  const manifest = {};
  const credits = {};

  for (const v of VEHICLES) {
    const { photos, query } = await photosFor(v);
    if (photos.length === 0) {
      console.log(`#${v.id} ${v.make} ${v.model}: NO RESULTS`);
      manifest[v.id] = [];
      continue;
    }
    const chosen = photos.slice(0, IMAGES_PER_CAR);
    const paths = [];
    const cred = [];
    for (let i = 0; i < chosen.length; i++) {
      const photo = chosen[i];
      const src = photo.src.large2x || photo.src.large || photo.src.original;
      const file = `${v.id}-${i + 1}.webp`;
      const dest = path.join(PUBLIC_DIR, file);
      try {
        const buffer = await downloadBuffer(src);
        const bytes = await saveWebp(buffer, dest);
        paths.push(`/vehicles/${file}`);
        cred.push({ photographer: photo.photographer, url: photo.url });
        void bytes;
      } catch (e) {
        console.warn(`  ! download ${file}: ${e.message}`);
      }
    }
    manifest[v.id] = paths;
    credits[v.id] = cred;
    console.log(
      `#${v.id} ${v.make} ${v.model}: ${paths.length} imgs  (q="${query}")`
    );
  }

  const header =
    "// AUTO-GENERATED by scripts/fetch-car-images.mjs — do not edit by hand.\n" +
    "// Real vehicle photos sourced from Pexels (https://pexels.com).\n\n";
  const body =
    "export const VEHICLE_IMAGES: Record<string, string[]> = " +
    JSON.stringify(manifest, null, 2) +
    ";\n";
  await writeFile(MANIFEST, header + body);

  const total = Object.values(manifest).reduce((n, a) => n + a.length, 0);
  console.log(`\nDone. ${total} images downloaded. Manifest -> ${MANIFEST}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
